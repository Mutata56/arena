-- Учебная база склада wms_demo, версия для PostgreSQL.
--
-- Схема называется dbo намеренно. В MS SQL это схема по умолчанию, и все примеры
-- в конспектах написаны как dbo.stock. Postgres разрешает завести схему с таким же
-- именем, и тогда одно и то же имя таблицы работает дословно в обоих диалектах —
-- ученик не отвлекается на переименования там, где разговор вообще не про них.
--
-- Совместимостных заглушек (GETDATE, ISNULL, LEN) здесь нет и не будет: курс учит
-- различать диалекты, а не прятать разницу. Где T-SQL и PostgreSQL расходятся,
-- об этом сказано в конспекте, а не подделано в базе.

DROP SCHEMA IF EXISTS dbo CASCADE;
CREATE SCHEMA dbo;
SET search_path TO dbo, public;

---------- 1. справочники ----------
CREATE TABLE dbo.sku (
    skuid     varchar(20)   NOT NULL PRIMARY KEY,  -- артикул, он же первичный ключ
    descr     varchar(100)  NOT NULL,              -- название
    uom       varchar(10)   NOT NULL DEFAULT 'PC', -- единица измерения
    weight    decimal(9,3)  NULL,                  -- вес единицы, у весовых NULL
    shelflife int           NULL                   -- срок годности в днях
);

CREATE TABLE dbo.loc (
    loc     varchar(10) NOT NULL PRIMARY KEY,
    zone    varchar(10) NOT NULL,
    loctype varchar(10) NOT NULL
);

CREATE TABLE dbo.lot (
    lot     varchar(10) NOT NULL PRIMARY KEY,
    skuid   varchar(20) NOT NULL REFERENCES dbo.sku(skuid),
    mfgdate date NULL,
    expdate date NULL
);

---------- 2. движение ----------
CREATE TABLE dbo.stock (
    skuid        varchar(20)   NOT NULL REFERENCES dbo.sku(skuid),
    loc          varchar(10)   NOT NULL REFERENCES dbo.loc(loc),
    lot          varchar(10)   NOT NULL REFERENCES dbo.lot(lot),
    qty          decimal(12,3) NOT NULL DEFAULT 0,
    qtyallocated decimal(12,3) NOT NULL DEFAULT 0,
    CONSTRAINT pk_stock PRIMARY KEY (skuid, loc, lot)
);

-- IDENTITY(1,1) из T-SQL это GENERATED BY DEFAULT AS IDENTITY в стандарте.
-- «BY DEFAULT», а не «ALWAYS»: так свой orderkey можно подставить руками,
-- когда задача про это, и не спотыкаться об OVERRIDING SYSTEM VALUE.
CREATE TABLE dbo.orders (
    orderkey  int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer  varchar(60)  NOT NULL,
    orderdate timestamp(0) NOT NULL,
    status    varchar(10)  NOT NULL DEFAULT 'NEW'
);

CREATE TABLE dbo.orderdetail (
    orderkey   int           NOT NULL REFERENCES dbo.orders(orderkey),
    linenum    smallint      NOT NULL,
    skuid      varchar(20)   NOT NULL REFERENCES dbo.sku(skuid),
    qtyordered decimal(12,3) NOT NULL,
    qtypicked  decimal(12,3) NOT NULL DEFAULT 0,
    CONSTRAINT pk_orderdetail PRIMARY KEY (orderkey, linenum)
);

CREATE TABLE dbo.pickdetail (
    pickkey  int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orderkey int           NOT NULL,
    linenum  smallint      NOT NULL,
    skuid    varchar(20)   NOT NULL,
    loc      varchar(10)   NOT NULL,
    lot      varchar(10)   NOT NULL,
    qty      decimal(12,3) NOT NULL,
    status   varchar(10)   NOT NULL DEFAULT 'RELEASED',
    CONSTRAINT fk_pick_od FOREIGN KEY (orderkey, linenum)
        REFERENCES dbo.orderdetail(orderkey, linenum)
);

