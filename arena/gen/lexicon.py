"""Слова, до которых ученик ещё не дошёл.

Промпт про это знает: в нём есть раздел «Про это ещё рано» со списком будущих
нод. Но промпт это просьба. Модель честно обходит запретную тему в самом вопросе
и тут же роняет «ошибка компиляции» в неверный вариант, потому что там оно как бы
не считается. Считается: ученик читает все четыре варианта, и незнакомое слово
в третьем варианте ровно так же отправляет его гуглить.

Поэтому тот же запрет продублирован здесь проверкой, и запись с чужим словом
в банк просто не попадает.

Список нарочно короткий. Сюда идёт только то, что роадмап вводит отдельной нодой
и до неё нигде не встречается: слово, которое ученик уже видел в конспекте,
запрещать нельзя, иначе валидатор начнёт резать нормальные вопросы.
"""

from __future__ import annotations

import re
import sqlite3

# Код ноды, начиная с которой слово разрешено, и сам шаблон.
TERMS: list[tuple[str, str]] = [
    # Пороги считаны по волту: слово разрешено с той ноды, где оно впервые
    # встречается в самом конспекте. Роадмап дробили, ноды 1.031-1.034 встали
    # между 1.06 и 1.04, и старые пороги (всё на 1.03) начали резать генерацию
    # у нод, которые эти термины как раз и вводят.
    ("1.023", r"компилятор\w*|компиляц\w+|компилир\w+|скомпил\w+|\bjavac\b|"
              r"собер[её]тся|соберут|сборк\w+\s+код\w*"),
    ("1.032", r"байт-?код\w*"),
    ("1.033", r"\bJVM\b|виртуальн\w*\s+машин\w*"),
    ("1.03", r"\bJDK\b|\bJRE\b"),
    ("1.08", r"\bjshell\b"),
    ("1.14", r"\bIntelliJ\b|\bIDEA\b"),
    # `String[] args` в подписи ученик видит с первой ноды, но что это такое
    # и как оттуда что-то достать, разбирают в 1.18. Поэтому запрещено не слово
    # args, а обращение к нему: args[0] и разговоры про аргументы запуска.
    ("1.18", r"args\s*\[|аргумент\w*\s+(?:командн\w+|запуск\w+|строк\w+)|"
             r"командн\w+\s+строк\w+|с\s+аргумент\w+"),
    # Обратный слэш до 1.11 не проходили ни в каком виде: ни `\n` в строке,
    # ни путь `C:\Users\...`. В русском тексте он не встречается вообще, так что
    # ловим любой — и в коде, и в самой формулировке вопроса.
    ("1.11", r"\\"),
    # Переменные это уже второй этап. Весь первый — это println с готовым текстом,
    # поэтому объявление с присваиванием в вопросе первого этапа не имеет права быть.
    ("2.01", r"\b(?:int|long|double|float|boolean|char|String)\s+\w+\s*="),
    # Константы разбирают в 3.09. До неё `final` в вопросе про переменные это
    # разговор про то, чего ученик не проходил.
    ("3.09", r"\bfinal\b|константа|константы|константу"),
]


def _place(conn: sqlite3.Connection, code: str) -> tuple[int, int] | None:
    row = conn.execute(
        "SELECT s.num AS num, n.seq AS seq FROM nodes n JOIN stages s ON s.id = n.stage_id "
        "WHERE n.code = ?", (code,),
    ).fetchone()
    return (row["num"], row["seq"]) if row else None


def ban_for(conn: sqlite3.Connection, node: sqlite3.Row | None) -> list[tuple[str, re.Pattern]]:
    """Что на этой ноде под запретом: термины, которые вводятся позже неё."""
    if node is None:
        return []
    here = _place(conn, node["code"])
    if here is None:
        return []
    out = []
    for code, pattern in TERMS:
        there = _place(conn, code)
        if there is not None and there > here:
            out.append((code, re.compile(pattern, re.IGNORECASE)))
    return out


def check(text: str, name: str, ban: list[tuple[str, re.Pattern]]) -> None:
    """Бросить Bad, если в тексте слово из будущей ноды."""
    from .validate import Bad

    if not text or not ban:
        return
    for code, rx in ban:
        hit = rx.search(text)
        if hit:
            raise Bad(f"{name}: слово {hit.group(0)!r} из ноды {code}, "
                      f"ученик до неё ещё не дошёл")
